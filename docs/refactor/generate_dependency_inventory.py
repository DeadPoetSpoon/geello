"""Reproduce the M3 candidate inventory without changing dependency resolution.

Uses only Python's standard library and locked Cargo metadata. The all-target
resolver graph includes packages that are not built on the current host.
"""
from pathlib import Path
import hashlib
import json
import re
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[2]


def cell(value):
    return str(value or "-").replace("|", "\\|").replace("\n", " ")


def table(headers, rows):
    return ["| " + " | ".join(headers) + " |",
            "| " + " | ".join("---" for _ in headers) + " |",
            *("| " + " | ".join(cell(v) for v in row) + " |" for row in rows), ""]


def main():
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--all-features", "--locked", "--format-version", "1"],
        cwd=ROOT, text=True, encoding="utf-8"))
    lock_bytes = (ROOT / "Cargo.lock").read_bytes()
    lock = tomllib.loads(lock_bytes.decode("utf-8"))
    checksums = {(p["name"], p["version"], p.get("source")): p.get("checksum", "workspace")
                 for p in lock["package"]}
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    packages = sorted(metadata["packages"], key=lambda p: (p["name"], p["version"]))
    by_id = {p["id"]: p for p in packages}
    root = by_id[metadata["resolve"]["root"]]
    previous = (ROOT / "docs/refactor/07-m2-dependency-closure.md").read_text(encoding="utf-8")
    old = set(re.findall(r"\| `([^`]+)` \| `([^`]+)` \| `(?:registry|-)" , previous))
    added = [p for p in packages if (p["name"], p["version"]) not in old and p["name"] != "geello"]
    lines = ["# M3 candidate dependency closure", "",
        "Status: **candidate; G-01 remains pending owner review**. On 2026-11-13 the owner authorized M3 candidate-closure compatibility tests and separately approved `zip = 9.5.1`, default features disabled, only `deflate-flate2-zlib-rs`. This inventory does not grant formal transitive/native/license approval.", "",
        "Generated by `python docs/refactor/generate_dependency_inventory.py` from locked all-feature/all-target Cargo metadata. Platform-conditioned packages and build scripts appear even when not built on Windows MSVC. Sources are canonical Cargo sources; local registry replacement/mirror transport is not a different package source.", "",
        f"Lockfile SHA-256: `{hashlib.sha256(lock_bytes).hexdigest()}`. Packages including workspace: **{len(packages)}**. Package versions added relative to the M2 inventory: **{len(added)}**.", "",
        "Accepted native codec pins are retained: LZ4 1.28.1 / lz4-sys 1.11.1+lz4-1.10.0 and Zstd 0.13.4 / zstd-safe 7.4.0 / zstd-sys 2.1.2+zstd.1.5.7. Foyer response compression is disabled, but its native codec dependency closure still builds. ZIP Deflate uses Rust zlib-rs; TIFF may unify additional flate2 Rust features. No native PROJ, SQLite business catalog, TLS/authentication helper or container packages were introduced.", "",
        "## Root feature composition", ""]
    lines += table(["Feature", "Members"], [(f"`{name}`", ", ".join(members))
                                            for name, members in sorted(root["features"].items())])
    lines += ["## Package/version delta from M2", ""]
    lines += table(["Package", "Version", "Declared license"],
                   [(p["name"], p["version"], p.get("license") or "REVIEW: license-file") for p in added])
    lines += ["## Complete source, checksum, license and feature inventory", "",
        "Declared SPDX expressions and license-file pointers require a separate notices review; they do not certify the license of bundled C/C++ sources. No third-party checksum may be missing.", ""]
    rows = []
    for p in packages:
        checksum = checksums[(p["name"], p["version"], p.get("source"))]
        assert checksum and (p.get("source") is None or checksum != "workspace")
        rows.append((f'`{p["name"]}`', f'`{p["version"]}`', p.get("source") or "workspace",
                     f"`{checksum}`", p.get("license") or p.get("license_file") or "REVIEW",
                     p.get("repository"), ", ".join(nodes[p["id"]]["features"])))
    lines += table(["Package", "Version", "Source", "Checksum", "Declared license", "Repository", "Resolved features"], rows)
    lines += ["## Native links and build-script inventory", "",
        "Native source builds require the platform compiler/linker/SDK. Windows compatibility used Rust/Cargo 1.96.0 and MSVC; Linux/musl, Vulkan driver mappings and image runtime licenses remain G-10/G-11/M5 work. Build-script presence alone does not imply native C code.", ""]
    lines += table(["Package", "Version", "links", "Build script"],
                   [(p["name"], p["version"], p.get("links"),
                     "yes" if any("custom-build" in t["kind"] for t in p["targets"]) else "no")
                    for p in packages if p.get("links") or any("custom-build" in t["kind"] for t in p["targets"])])
    lines += ["## Exact dependency edges", "",
        "Each edge records Cargo dependency kind and target expression. Resolved features above are the all-target union, not a platform-minimal binary inventory.", ""]
    edge_rows = []
    for p in packages:
        for dep in nodes[p["id"]]["deps"]:
            child = by_id[dep["pkg"]]
            for kind in dep["dep_kinds"]:
                edge_rows.append((p["name"] + " " + p["version"], child["name"] + " " + child["version"],
                                  kind["kind"] or "normal", kind["target"] or "all targets"))
    lines += table(["Parent", "Dependency", "Kind", "Target"], edge_rows)
    output = ROOT / "docs/refactor/08-m3-dependency-closure.md"
    output.write_text("\n".join(lines), encoding="utf-8")
    artifacts = ROOT / "assets/test"
    artifacts.mkdir(parents=True, exist_ok=True)
    (artifacts / "m3-candidate-metadata.json").write_text(json.dumps(metadata, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {output.name}: {len(packages)} packages, {len(added)} additions, {len(edge_rows)} edges")


if __name__ == "__main__":
    main()
